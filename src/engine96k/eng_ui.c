#include "eng_ui.h"

// Compact 5x6 Analytic Glyph Bitmasks (30 bits packed into uint32_t!)
// Rendered smoothly via rounded SDF stroke bridging in UI shader (zero font bloat!)
#define G56(r0,r1,r2,r3,r4,r5) \
    (((uint32_t)(r0)) | ((uint32_t)(r1)<<5) | ((uint32_t)(r2)<<10) | \
     ((uint32_t)(r3)<<15) | ((uint32_t)(r4)<<20) | ((uint32_t)(r5)<<25))

uint32_t ui_glyph_mask(char ch) {
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);
    switch (ch) {
        case 'A': return G56(0x0E,0x11,0x11,0x1F,0x11,0x11);
        case 'B': return G56(0x0F,0x11,0x0F,0x11,0x11,0x0F);
        case 'C': return G56(0x0E,0x11,0x01,0x01,0x11,0x0E);
        case 'D': return G56(0x0F,0x11,0x11,0x11,0x11,0x0F);
        case 'E': return G56(0x1F,0x01,0x0F,0x01,0x01,0x1F);
        case 'F': return G56(0x1F,0x01,0x0F,0x01,0x01,0x01);
        case 'G': return G56(0x0E,0x11,0x01,0x1D,0x11,0x0E);
        case 'H': return G56(0x11,0x11,0x1F,0x11,0x11,0x11);
        case 'I': return G56(0x0E,0x04,0x04,0x04,0x04,0x0E);
        case 'J': return G56(0x1C,0x08,0x08,0x08,0x09,0x06);
        case 'K': return G56(0x11,0x09,0x07,0x09,0x11,0x11);
        case 'L': return G56(0x01,0x01,0x01,0x01,0x01,0x1F);
        case 'M': return G56(0x11,0x1B,0x15,0x11,0x11,0x11);
        case 'N': return G56(0x11,0x13,0x15,0x19,0x11,0x11);
        case 'O': return G56(0x0E,0x11,0x11,0x11,0x11,0x0E);
        case 'P': return G56(0x0F,0x11,0x11,0x0F,0x01,0x01);
        case 'Q': return G56(0x0E,0x11,0x11,0x15,0x09,0x16);
        case 'R': return G56(0x0F,0x11,0x11,0x0F,0x09,0x11);
        case 'S': return G56(0x1E,0x01,0x0E,0x10,0x10,0x0F);
        case 'T': return G56(0x1F,0x04,0x04,0x04,0x04,0x04);
        case 'U': return G56(0x11,0x11,0x11,0x11,0x11,0x0E);
        case 'V': return G56(0x11,0x11,0x11,0x11,0x0A,0x04);
        case 'W': return G56(0x11,0x11,0x11,0x15,0x1B,0x11);
        case 'X': return G56(0x11,0x0A,0x04,0x04,0x0A,0x11);
        case 'Y': return G56(0x11,0x0A,0x04,0x04,0x04,0x04);
        case 'Z': return G56(0x1F,0x08,0x04,0x02,0x01,0x1F);
        case '0': return G56(0x0E,0x11,0x19,0x15,0x13,0x0E);
        case '1': return G56(0x04,0x06,0x04,0x04,0x04,0x0E);
        case '2': return G56(0x0E,0x11,0x08,0x06,0x01,0x1F);
        case '3': return G56(0x0F,0x10,0x0E,0x10,0x10,0x0F);
        case '4': return G56(0x08,0x0C,0x0A,0x1F,0x08,0x08);
        case '5': return G56(0x1F,0x01,0x0F,0x10,0x10,0x0F);
        case '6': return G56(0x0E,0x01,0x0F,0x11,0x11,0x0E);
        case '7': return G56(0x1F,0x10,0x08,0x04,0x04,0x04);
        case '8': return G56(0x0E,0x11,0x0E,0x11,0x11,0x0E);
        case '9': return G56(0x0E,0x11,0x11,0x1E,0x10,0x0E);
        case '+': return G56(0x00,0x04,0x04,0x1F,0x04,0x04);
        case '-': return G56(0x00,0x00,0x00,0x1F,0x00,0x00);
        case '/': return G56(0x10,0x08,0x04,0x04,0x02,0x01);
        case '%': return G56(0x13,0x13,0x08,0x04,0x19,0x19);
        case ':': return G56(0x00,0x04,0x00,0x00,0x04,0x00);
        case '.': return G56(0x00,0x00,0x00,0x00,0x00,0x04);
        case ',': return G56(0x00,0x00,0x00,0x00,0x04,0x02);
        case '\'':return G56(0x04,0x04,0x00,0x00,0x00,0x00);
        case '!': return G56(0x04,0x04,0x04,0x04,0x00,0x04);
        case '?': return G56(0x0E,0x11,0x08,0x04,0x00,0x04);
        case '*': return G56(0x04,0x15,0x0E,0x15,0x04,0x00);
        case '(': return G56(0x08,0x04,0x04,0x04,0x04,0x08);
        case ')': return G56(0x02,0x04,0x04,0x04,0x04,0x02);
        case '>': return G56(0x02,0x04,0x08,0x04,0x02,0x00);
        case '<': return G56(0x08,0x04,0x02,0x04,0x08,0x00);
        case '^': return G56(0x04,0x0E,0x15,0x04,0x04,0x04);
        default:  return 0;
    }
}

void ui_push_panel(RenderPacket *pkt, float x0, float y0, float x1, float y1,
                   uint32_t bg, uint32_t border_col, float radius, float border_px) {
    if (pkt->ui_prim_count >= MAX_UI_PRIMS) return;
    pkt->ui_prims[pkt->ui_prim_count++] = (UiPrim){
        x0, y0, x1, y1, 0.0f, 0.0f, 1.0f, 1.0f, bg, border_col, radius, border_px, 0, 0, 0, 0
    };
}

void ui_push_text(RenderPacket *pkt, float x, float y, float h_px, const char *str, uint32_t col, bool center_x) {
    int len = (int)strlen(str);
    float cw = h_px * 0.76f;
    float adv = h_px * 0.90f;
    if (center_x) x -= (len * adv - (adv - cw)) * 0.5f;
    for (int i = 0; i < len && pkt->ui_prim_count < MAX_UI_PRIMS; i++) {
        uint32_t mask = ui_glyph_mask(str[i]);
        if (mask != 0) {
            pkt->ui_prims[pkt->ui_prim_count++] = (UiPrim){
                x, y, x + cw, y + h_px, 0.0f, 0.0f, 1.0f, 1.0f,
                col, rgba8(10, 12, 22, 195), 0.0f, 0.0f, 1, mask, 0, 0
            };
        }
        x += adv;
    }
}
